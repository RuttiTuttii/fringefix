/* PRIMARYLANGID русского в Windows, значение из winnt.h: модуль не зависит от платформы */
#define FF_LANGID_RUSSIAN 0x19

ff_lang ff_i18n_resolve(int mode, unsigned primary_langid)
{
    if (mode == 1) {
        return FF_LANG_RU;
    }
    if (mode == 2) {
        return FF_LANG_EN;
    }
    return primary_langid == FF_LANGID_RUSSIAN ? FF_LANG_RU : FF_LANG_EN;
}

void ff_i18n_set(ff_lang lang)
{
    g_lang = lang;
}

const wchar_t *ff_tr_lang(ff_lang lang, str_id id)
{
    const wchar_t *s;

    if (id < 0 || id >= S_COUNT) {
        return L"";
    }
    s = lang == FF_LANG_RU ? RU[id] : EN[id];
    return s ? s : L"";
}

ff_lang ff_i18n_get(void)
{
    return g_lang;
}

const wchar_t *ff_tr(str_id id)
{
    return ff_tr_lang(g_lang, id);
}
