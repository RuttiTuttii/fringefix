#ifndef FRINGEFIX_PATTERN_H
#define FRINGEFIX_PATTERN_H

#include <windows.h>

/* тестовый паттерн рядом с окном anchor: справа от него, той же высоты и вполовину уже; если справа
 * не хватает места на мониторе, слева. две равные части по высоте, верхняя чёрным по белому, нижняя белым
 * по чёрному, каждая из трёх полос: тонкие линии 1 px с шагом 14 px, толстые 5 px с шагом 10 px
 * (слева горизонтальные, справа вертикальные) и алфавит. толщина линий в физических пикселях, шаг при
 * 96 dpi и растёт вместе с dpi окна anchor.
 * окно не забирает фокус; клик по нему закрывает его. повторный вызов только переставляет окно */
void pattern_show(HINSTANCE inst, HWND anchor);

/* переставляет открытое окно паттерна вслед за anchor; ничего не делает, если паттерн закрыт */
void pattern_follow(HWND anchor);

/* закрывает окно паттерна, если оно открыто */
void pattern_close(void);

/* открыт ли паттерн сейчас */
int pattern_is_open(void);

#endif
