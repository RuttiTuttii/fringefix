#ifndef FRINGEFIX_UI_MENUBAR_H
#define FRINGEFIX_UI_MENUBAR_H

#include <windows.h>

/* полоса меню в верхней части окна настроек: Файл, Правка, Сервис, Справка. системное меню окна в тёмной теме
 * осталось бы светлым, поэтому полоса рисуется общей палитрой, а пункты открывают обычные всплывающие меню.
 * выбранная команда уходит окну сообщением WM_COMMAND с идентификатором из ui_state.h */

/* рисует полосу шириной width пикселей; item под курсором или с открытым меню подсвечивается */
void menubar_paint(HDC dc, int dpi, int width);

/* номер пункта полосы под точкой окна или -1 */
int menubar_hit(int x, int y);

/* подсветка пункта под курсором, -1 снимает; перерисовывает только полосу */
void menubar_hover(HWND h, int item);

/* открывает меню пункта под его заголовком и отправляет выбранную команду окну h */
void menubar_open(HWND h, int item);

#endif
