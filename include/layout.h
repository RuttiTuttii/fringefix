#ifndef FRINGEFIX_LAYOUT_H
#define FRINGEFIX_LAYOUT_H

/* раскладка сабпикселей матрицы; QD-OLED первых четырёх поколений сделаны треугольником:
 * красный и синий рядом снизу, зелёный над ними посередине */
typedef enum {
    FF_LAYOUT_NONE,
    FF_LAYOUT_QD_TRIANGLE,
    FF_LAYOUT_COUNT
} ff_layout;

/* считает сдвиги трёх каналов из геометрии сабпикселей. канал должен показывать картинку в точке,
 * где он стоит физически, поэтому сдвиг равен минус смещению сабпикселя от центра пикселя.
 * kx и ky от -3 до 3 масштабируют смещения по осям; минус зеркалит раскладку: зелёный оказывается снизу,
 * красный и синий меняются местами. результат зажимается в пределы FF_SHIFT_LIMIT.
 * FF_LAYOUT_NONE даёт нули: полоски RGB в LCD закрывает ClearType самой системы */
void ff_layout_shifts(ff_layout layout, double kx, double ky, float shift[3][2]);

#endif
