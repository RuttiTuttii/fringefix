#ifndef FRINGEFIX_CRASH_H
#define FRINGEFIX_CRASH_H

#include "config.h"

/* аварийный журнал: при необработанном исключении пишет в crash.log рядом с настройками код и адрес сбоя, модуль со смещением,
 * найденные в стеке адреса возврата нашего exe и последний этап каждого потока захвата. без символов Windows этого хватает,
 * чтобы по той же сборке найти функцию через nm; сам процесс после записи завершается как обычно */
void crash_install(void);

/* отмечает этап работы потока захвата монитора worker; строка должна жить вечно, то есть быть литералом */
void crash_mark(int worker, const char *stage);

#endif
