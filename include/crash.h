#ifndef FRINGEFIX_CRASH_H
#define FRINGEFIX_CRASH_H

#include "config.h"

/* аварийный журнал: при необработанном исключении пишет в crash.log и crash.dmp рядом с настройками код и имя исключения, адрес сбоя, регистры, GetLastError, модуль со смещением,
 * найденные в стеке адреса возврата нашего exe и последний этап каждого потока захвата. без символов Windows этого хватает,
 * чтобы по той же сборке найти функцию через nm; сам процесс после записи завершается как обычно */
void crash_install(void);

/* отмечает этап работы потока захвата монитора worker; строка должна жить вечно, то есть быть литералом.
 * заодно запоминает номер вызывающего потока: при сбое по нему читается, где стоят остальные потоки */
void crash_mark(int worker, const char *stage);

/* последний отмеченный этап монитора worker или "-" */
const char *crash_stage(int worker);

/* оставляет потоку запас стека на обработчик исключения: зовётся в начале каждого потока */
void crash_guard_stack(void);

#endif
