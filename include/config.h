#ifndef FRINGEFIX_CONFIG_H
#define FRINGEFIX_CONFIG_H

#include <stddef.h>

#include "hotkey.h"

/* длина строки списка программ: при 15 символах на имя это около семидесяти приложений */
#define FF_APPS_MAX 1024

/* длина пути в UTF-8: запоминается последняя папка кнопок ReShade, путь Windows до 260 символов */
#define FF_PATH_MAX 600

/* пределы значений: сдвиг канала в пикселях и резкость, минус у резкости смягчает картинку */
#define FF_SHIFT_LIMIT 2.0
#define FF_SHARPEN_LIMIT 1.0

/* сколько мониторов программа ведёт одновременно: выходы всех видеокарт подряд, лишние игнорируются */
#define FF_MAX_MONITORS 8

/* вид картинки одного монитора: то, что хранит профиль, и флаг работы фильтра на этом мониторе */
typedef struct {
    /* на сколько пикселей экрана уезжает содержимое канала: [r, g, b][x, y]; плюс означает вправо и вниз */
    float shift[3][2];
    /* резкость от -1 до 1 */
    float sharpen;
    /* фильтр на этом мониторе включён; общий выключатель (хоткей, трей) действует поверх: работает, если включены оба */
    int enabled;
} ff_view;

/* настройки; модуль не зависит от платформы, чтобы тестироваться без Windows */
typedef struct {
    /* вид картинки каждого монитора, индекс это номер выхода (выходы всех видеокарт подряд, с нуля) */
    ff_view view[FF_MAX_MONITORS];
    /* монитор, настройки которого показаны в окне; на работу других мониторов не влияет */
    int monitor;
    /* проверять обновления при запуске, 0 или 1 */
    int check_updates;
    /* получать бета-версии при проверке обновлений, 0 или 1; релизы-беты помечены на GitHub как prerelease */
    int beta;
    /* глобальные сочетания: включить или выключить оверлей и закрыть программу; vk = 0 выключает сочетание */
    ff_hotkey hotkey_toggle;
    ff_hotkey hotkey_quit;
    /* автопауза оверлея: 0 выключена, 1 в полноэкранных приложениях, 2 в полноэкранных и 3D-приложениях,
     * 3 только в 3D-приложениях */
    int auto_pause;
    /* приоритет GPU-потока оверлея от -7 до 7, ниже ноля уступает видеокарту игре */
    int gpu_priority;
    /* язык интерфейса: 0 как в системе, 1 русский, 2 английский */
    int language;
    /* тема окон: 0 как в системе, 1 светлая, 2 тёмная */
    int theme;
    /* вести локальную статистику для отчёта: 0 или 1; сама по себе никуда не отправляется */
    int stats;
    /* движок обработки: 0 классический, 1 сравнение кадров на compute-шейдере,
     * 2 то же и фильтр одним ядром 3x3 вместо 18 чтений на пиксель (по умолчанию); результат на экране один и тот же.
     * на мониторе, где сдвиги каналов разнесены больше чем на пиксель, окна ядра встают в разные клетки и девять чтений
     * на пиксель превращаются в двадцать семь, поэтому там вместо движка 2 работает движок 1 (см. gfx_upload) */
    int engine;
    /* способ вывода кадра (бета): 0 с ожиданием вертикальной синхронизации, как всегда; 1 без ожидания (tearing),
     * вывод не держит поток захвата; если система не умеет, остаётся 0 */
    int present_mode;
    /* имена exe через точку с запятой: всегда на паузу и никогда не на паузу */
    char pause_apps[FF_APPS_MAX];
    char ignore_apps[FF_APPS_MAX];
    /* последняя папка, где пользователь был по кнопкам установки, удаления и скачивания аддона ReShade; UTF-8 */
    char reshade_dir[FF_PATH_MAX];
    /* служебное для разбора: файл старого вида (одни сдвиги на всё) встретился, его значения лежат в view[0]
     * и переезжают на монитор из ключа monitor; наружу не используется */
    int legacy_view;
} ff_config;

/* все сдвиги нулевые: оверлей ничего не меняет; фильтр включён только на мониторе 0 */
void ff_config_defaults(ff_config *cfg);

/* вид монитора по номеру; номер вне диапазона зажимается */
ff_view *ff_config_view(ff_config *cfg, int index);
const ff_view *ff_config_view_const(const ff_config *cfg, int index);

/* все сдвиги и резкость в ноль, флаг включения остаётся */
void ff_view_reset(ff_view *v);

/* разбирает ini из строки, возвращает число принятых ключей; мусор и неизвестные ключи пропускает */
int ff_config_parse(const char *text, ff_config *cfg);

/* пишет ini в буфер вместе с комментариями; возвращает длину или -1, если буфер мал */
int ff_config_format(const ff_config *cfg, char *buf, size_t n);

#endif
