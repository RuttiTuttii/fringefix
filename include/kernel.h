#ifndef FRINGEFIX_KERNEL_H
#define FRINGEFIX_KERNEL_H

/* фильтр канала (сдвиг на долю пикселя плюс лапласиан) линеен и одинаков по всему экрану, поэтому сводится
 * к одному окну 3x3 на канал. модуль без платформенного кода: те же числа получает шейдер ядра, а тест
 * сверяет их с прямым расчётом по формулам классического шейдера */
typedef struct {
    /* смещение центра окна относительно пикселя вывода: x, y */
    int base[3][2];
    /* веса окна по строкам: w[канал][строка * 3 + столбец] */
    float w[3][9];
    /* 1, если у всех трёх каналов окно стоит в одной клетке и девять пикселей читаются один раз на все каналы */
    int shared;
} ff_kernel;

/* считает окна из сдвигов трёх каналов подряд (r.x, r.y, g.x, g.y, b.x, b.y, как shift[3][2] в конфиге) и резкости так же, как классический шейдер:
 * сдвиги центрируются вокруг нуля, сила лапласиана min(1.72 * f^2, 0.35) + резкость * 0.35,
 * f это дробная часть сдвига. веса билинейной интерполяции берутся точными, а не 8-битными аппаратными */
void ff_kernel_build(const float shift[6], float sharpen, ff_kernel *k);

#endif
